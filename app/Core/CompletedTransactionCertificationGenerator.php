    public function generate(array $transactions, array $settings, string $pbcNumber, string $certificateDate): array
    {
        self::ensureSpreadsheetAutoload();
        if ($transactions === []) {
            throw new RuntimeException('No completed transactions were found for the selected period.');
        }
        if (!is_file(self::templatePath())) {
            throw new RuntimeException('The PBC Excel template is missing.');
        }

        $spreadsheet = IOFactory::load(self::templatePath());
        $sheet = $spreadsheet->getActiveSheet();
        foreach (['I3:J3', 'I4:J4', 'A7:E7', 'A8:E8', 'B10:J10', 'B11:J11', 'A15:B15', 'C15', 'D15:E15', 'F15:G15', 'H15', 'I15:J15', 'F33:J33', 'A40:D40'] as $guideRange) {
            $sheet->getStyle($guideRange)->getFill()->setFillType(Fill::FILL_NONE);
        }
        $extraRows = count($transactions) - 1;
        if ($extraRows > 0) {
            $sheet->insertNewRowBefore(self::TOTAL_ROW, $extraRows);
        }

        $templateStyle = $sheet->getStyle('A' . self::DATA_ROW . ':J' . self::DATA_ROW);
        $templateHeight = $sheet->getRowDimension(self::DATA_ROW)->getRowHeight();
        foreach ($transactions as $index => $transaction) {
            $row = self::DATA_ROW + $index;
            if ($index > 0) {
                $sheet->duplicateStyle($templateStyle, 'A' . $row . ':J' . $row);
                $sheet->getRowDimension($row)->setRowHeight($templateHeight);
                foreach (['A:B', 'D:E', 'F:G', 'I:J'] as $columns) {
                    [$from, $to] = explode(':', $columns);
                    $sheet->mergeCells($from . $row . ':' . $to . $row);
                }
            }

            $amount = self::numericAmount((string) ($transaction['amount'] ?? ''));
            $sheet->setCellValue('A' . $row, (string) ($settings['PBC_BANK_ACCOUNT'] ?? ''));
            $sheet->setCellValueExplicit('C' . $row, (string) ($transaction['check_no'] ?? ''), \PhpOffice\PhpSpreadsheet\Cell\DataType::TYPE_STRING);
            $sheet->setCellValue('D' . $row, self::displayDate((string) ($transaction['completed_at'] ?? '')));
            $sheet->setCellValue('F' . $row, (string) ($transaction['payee'] ?? ''));
            $sheet->setCellValue('H' . $row, $amount);
            $sheet->setCellValue('I' . $row, (string) ($transaction['pr_purpose'] ?? $transaction['purpose'] ?? ''));
            $sheet->getStyle('A' . $row . ':J' . $row)->getAlignment()->setWrapText(true)->setVertical(Alignment::VERTICAL_CENTER);
            $sheet->getStyle('H' . $row)->getNumberFormat()->setFormatCode('#,##0.00');
            $sheet->getStyle('A' . $row . ':J' . $row)->getBorders()->getAllBorders()->setBorderStyle(Border::BORDER_THIN)->setColor(new Color('FF333333'));
        }

        $totalRow = self::TOTAL_ROW + $extraRows;
        $sheet->setCellValue('H' . $totalRow, '=SUM(H' . self::DATA_ROW . ':H' . ($totalRow - 1) . ')');
        $sheet->getStyle('H' . $totalRow)->getNumberFormat()->setFormatCode('#,##0.00');

        $values = [
            'PBCNO' => $pbcNumber,
            'PBCDATE' => strtoupper((new DateTimeImmutable($certificateDate))->format('F j, Y')),
            'BANKNAME' => trim((string) ($settings['PBC_BANK_NAME'] ?? '')),
            'BANKADDRESS' => trim((string) ($settings['PBC_BANK_ADDRESS'] ?? '')),
            'BRGY' => trim((string) ($settings['BRGY'] ?? '')) ?: '________________',
            'PUNONG_BARANGAY' => trim((string) ($settings['PUNONG_BARANGAY'] ?? '')) ?: '____________________________',
            'BARANGAY_TREASURER' => trim((string) ($settings['BARANGAY_TREASURER'] ?? '')) ?: '____________________________',
        ];
        $this->replacePlaceholders($sheet, $values);
        $this->assertNoUnresolvedPlaceholders($sheet);
        $lastRow = 42 + $extraRows;
        ReportPrintSettings::apply($sheet, 'A1:J' . $lastRow, $settings);

        $outputDir = dirname(__DIR__, 2) . '/storage/generated_reports';
        if (!is_dir($outputDir) && !mkdir($outputDir, 0777, true) && !is_dir($outputDir)) {
            throw new RuntimeException('Unable to create generated reports directory.');
        }
        $baseName = 'PBC_' . preg_replace('/[^A-Za-z0-9_-]+/', '_', $pbcNumber) . '_' . date('Ymd_His');
        $xlsxPath = $outputDir . '/' . $baseName . '.xlsx';
        $pdfPath = $outputDir . '/' . $baseName . '.pdf';
        try {
            IOFactory::createWriter($spreadsheet, 'Xlsx')->save($xlsxPath);
            $spreadsheet->disconnectWorksheets();
            if (!$this->convertToPdf($xlsxPath, $outputDir, $pdfPath)) {
                throw new RuntimeException('LibreOffice could not create the certification PDF.');
            }
        } finally {
            if (is_file($xlsxPath)) {
                unlink($xlsxPath);
            }
        }

        return ['pdf' => $pdfPath, 'number' => $pbcNumber, 'count' => count($transactions)];
    }

    private static function mergeAndSet(Worksheet $sheet, string $range, string $value): void
    {
        $sheet->mergeCells($range);
        $sheet->setCellValue(explode(':', $range)[0], $value);
    }

    private static function ensureSpreadsheetAutoload(): void
    {
        if (class_exists(IOFactory::class)) {
            return;
        }
        $localAutoload = dirname(__DIR__, 2) . '/vendor/autoload.php';
        $fallbackAutoload = 'C:/xampp/htdocs/FinanceSystem/vendor/autoload.php';
        if (is_file($localAutoload)) {
            require_once $localAutoload;
            return;
        }
        if (is_file($fallbackAutoload)) {
            require_once $fallbackAutoload;
            return;
        }
        throw new RuntimeException('PhpSpreadsheet autoload file was not found.');
    }

    private function replacePlaceholders(Worksheet $sheet, array $values): void
    {
        $highestColumn = Coordinate::columnIndexFromString($sheet->getHighestDataColumn());
        for ($row = 1; $row <= $sheet->getHighestDataRow(); $row++) {
            for ($column = 1; $column <= $highestColumn; $column++) {
                $cell = $sheet->getCell([$column, $row]);
                $value = $cell->getValue();
                if (!is_string($value) || $value === '' || str_starts_with($value, '=')) {
                    continue;
                }
                foreach ($values as $key => $replacement) {
                    $value = str_replace('${' . $key . '}', (string) $replacement, $value);
                }
                $cell->setValue($value);
            }
        }
    }

    private function convertToPdf(string $xlsxPath, string $outputDir, string $expectedPdfPath): bool
    {
        if (!is_file(self::SOFFICE)) {
            return false;
        }
        $profileDir = dirname(__DIR__, 2) . '/storage/libreoffice_profile_pbc';
        if (!is_dir($profileDir)) {
            mkdir($profileDir, 0777, true);
        }
        $command = '"' . self::SOFFICE . '" --headless --nologo --nodefault --nofirststartwizard --nolockcheck --norestore -env:UserInstallation=file:///'
            . str_replace('\\', '/', $profileDir) . ' --convert-to pdf --outdir ' . escapeshellarg($outputDir) . ' ' . escapeshellarg($xlsxPath) . ' 2>&1';
        $output = [];
        $code = 0;
        exec($command, $output, $code);

        return $code === 0 && is_file($expectedPdfPath);
    }

    private function assertNoUnresolvedPlaceholders(Worksheet $sheet): void
    {
        foreach ($sheet->getCellCollection()->getCoordinates() as $coordinate) {
            $value = $sheet->getCell($coordinate)->getValue();
            if (is_string($value) && preg_match('/\$\{[^}]+\}/', $value) === 1) {
                throw new RuntimeException('Unmapped PBC placeholder remains at cell ' . $coordinate . '.');
            }
        }
    }

    private static function numericAmount(string $value): float
    {
        $clean = preg_replace('/[^0-9.\-]/', '', $value);
        return is_numeric($clean) ? (float) $clean : 0.0;
    }

    private static function displayDate(string $value): string
    {
        $clean = trim($value);
        if ($clean === '') {
            return '';
        }
        try {
            return (new DateTimeImmutable($clean))->format('F j, Y');
        } catch (\Throwable) {
            return $clean;
        }
    }
